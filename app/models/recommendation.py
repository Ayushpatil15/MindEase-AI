"""Recommendation model.

Stores personalized recommendations generated by the rule-based engine.
"""

from datetime import datetime, timezone

from app.extensions import db


# Canonical recommendation categories
RECOMMENDATION_CATEGORIES = [
    'MINDFULNESS',
    'ACADEMIC',
    'PHYSICAL',
    'SOCIAL',
    'CLINICAL_SUPPORT',
]


class Recommendation(db.Model):
    """A personalized recommendation generated for a student."""

    __tablename__ = 'recommendations'
    __table_args__ = (
        db.Index('ix_rec_user_date', 'user_id', 'created_at'),
    )

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(
        db.Integer,
        db.ForeignKey('users.id', ondelete='CASCADE'),
        nullable=False,
        index=True,
    )

    # Category from RECOMMENDATION_CATEGORIES
    category = db.Column(db.String(30), nullable=False)

    title = db.Column(db.String(200), nullable=False)
    description = db.Column(db.Text, nullable=False)

    # Explains WHY this recommendation was suggested
    reason = db.Column(db.Text, nullable=False)

    created_at = db.Column(db.DateTime(timezone=True), nullable=False, default=lambda: datetime.now(timezone.utc))

    def __init__(self, **kwargs):
        super().__init__(**kwargs)

    def __repr__(self):
        return f'<Recommendation user={self.user_id} category={self.category} title={self.title!r}>'
